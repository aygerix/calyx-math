    #[test]
    fn interreduction_as_in_magma() {
        let r = |s: &[&str]| reduced(interreduce, s);
        assert_eq!(r(&["x*y - z", "y - z", "x - z"]), ["x - z", "y - z", "z^2 - z"]);
        assert_eq!(r(&["y^2 - x", "x*y - z^3", "y - z"]), ["x - z^2", "y - z"]);
        assert_eq!(r(&["2*x^2 - y", "4*x^2*y - z", "3*x*z"]), ["x^2 - 1/2*y", "x*z", "y^2 - 1/2*z"]);
        assert_eq!(r(&["x*y - z^2", "x - y", "y^2 + z^3"]), ["x - y", "y^2 - z^2", "z^3 + z^2"]);
        assert_eq!(r(&["0", "x", "2*x"]), ["x"]);
        assert!(r(&[]).is_empty());
        // Whatever the order of the input, the least leading monomials
        // reduce first.
        for s in [["x*y - z", "x*z - y", "x*y*z - 1"], ["x*y*z - 1", "x*z - y", "x*y - z"]] {
            assert_eq!(r(&s), ["x*y - z", "x*z - y", "y^2 - 1"]);
        }
        for s in [["x*y*z + x", "x*y - z", "x*z - y"], ["x*z - y", "x*y - z", "x*y*z + x"]] {
            assert_eq!(r(&s), ["x + y^2", "y^3 + z", "y^2*z + y"]);
        }
        assert_eq!(r(&["x*y^2 - 1", "x*y - z", "x*y^2*z - y"]), ["x*z - z", "y - z", "z^2 - 1"]);
        assert_eq!(r(&["x^2*y^2 - 1", "x*y^2 - z", "x^2*y - z"]), ["x^2*y - z", "x*y^2 - z", "x*z - 1"]);
        assert_eq!(r(&["x*y + z^2", "x*y + z", "x*z"]), ["x*y + z", "x*z", "z^2 - z"]);
        assert_eq!(r(&["x*y + y", "x*y + z", "y*z - 1"]), ["x*z + z", "y - z", "z^2 - 1"]);
    }

