//! Gröbner bases for calyx.
//!
//! This crate holds the algorithms behind Magma's chapter on Gröbner bases:
//! the monomial orders and the computation of bases. It depends on
//! calyx-flint only, so the algorithms can be tested without the
//! interpreter; polynomials cross the boundary as lists of terms
//! `(coefficient, exponents)` in the coefficient ring's `gr` context, and
//! are converted once per call to the engine's own representation.

mod basis;
mod buchberger;
mod f4;
mod fglm;
pub mod field;
mod modular;
pub mod order;
mod poly;

use std::rc::Rc;

use calyx_flint::gr::{Ctx, CtxKind, Elem};

use field::{Coefficients, Field};
use poly::{Poly, Ring};

pub use order::{Order, OrderArg, OrderError, Weights};

/// A polynomial as a list of terms: a coefficient and the exponents of the
/// variables, in any order.
pub type Terms = Vec<(Elem, Vec<u64>)>;

/// How a basis is computed, as Magma's parameters choose it.
#[derive(Clone, Copy, Debug, Default)]
pub struct Strategy {
    /// Over the rationals, compute with rationals throughout rather than
    /// modulo primes (GlobalModular := false). The modular method is Monte
    /// Carlo, as in Magma; this way is proven.
    pub rational: bool,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Error {
    /// The engine has no algorithm for this coefficient ring.
    Unsupported,
    /// An exponent of 2^32 or more.
    ExponentTooLarge,
}

/// Evaluate `$body` with `$f` bound to the engine's field for the
/// coefficient ring `$base`.
macro_rules! with_field {
    ($base:expr, $f:ident => $body:expr) => {
        match field::coefficients($base).ok_or(Error::Unsupported)? {
            Coefficients::Zp($f) => $body,
            Coefficients::Gr($f) => $body,
        }
    };
}

/// The reduced Gröbner basis of the ideal generated by `gens`, polynomials
/// in `n` variables over `base` with the monomial order `order`. As in
/// Magma, the basis is sorted by decreasing leading monomial and each
/// polynomial is monic with its terms in decreasing order; the zero ideal
/// has the empty basis.
pub fn groebner(base: &Rc<Ctx>, n: usize, order: &Order, gens: &[Terms]) -> Result<Vec<Terms>, Error> {
    groebner_with(base, n, order, gens, Strategy::default())
}

/// As `groebner`, computed as `strategy` says.
pub fn groebner_with(base: &Rc<Ctx>, n: usize, order: &Order, gens: &[Terms], strategy: Strategy) -> Result<Vec<Terms>, Error> {
    let ring = Ring { n, order: order.clone() };
    if modular(base, strategy) {
        if let Some(g) = modular::groebner(base, &ring, gens)? {
            return Ok(g);
        }
    }
    basis_of(base, &ring, gens, None)
}

/// Whether bases are lifted from bases modulo primes: over the rationals,
/// unless `strategy` says otherwise.
fn modular(base: &Ctx, strategy: Strategy) -> bool {
    !strategy.rational && matches!(base.kind(), CtxKind::Rationals)
}

/// The Gröbner basis of the ideal generated by `gens` truncated at degree
/// `d`: the pairs whose lcm has weighted degree more than `d`, the
/// variables having the weights `weights`, are ignored. It is reduced and
/// sorted as by `groebner`.
pub fn truncated_groebner(base: &Rc<Ctx>, n: usize, order: &Order, gens: &[Terms], weights: &[u64], d: i128) -> Result<Vec<Terms>, Error> {
    basis_of(base, &Ring { n, order: order.clone() }, gens, Some((weights, d)))
}

/// The normal form of `f` modulo `gb`, a Gröbner basis as `groebner`
/// returns it (with the same `base`, `n` and `order`).
pub fn normal_form(base: &Rc<Ctx>, n: usize, order: &Order, f: &Terms, gb: &[Terms]) -> Result<Terms, Error> {
    Ok(normal_forms(base, n, order, std::slice::from_ref(f), gb)?.pop().expect("one normal form"))
}

/// The remainders of the polynomials `fs` on division by `divisors` as in
/// `divide`: for a Gröbner basis, their normal forms.
pub fn normal_forms(base: &Rc<Ctx>, n: usize, order: &Order, fs: &[Terms], divisors: &[Terms]) -> Result<Vec<Terms>, Error> {
    let ring = Ring { n, order: order.clone() };
    with_field!(base, f => {
        let g = imports(&f, &ring, divisors)?;
        let active: Vec<usize> = (0..g.len()).filter(|&k| !g[k].is_zero()).collect();
        let masks: Vec<u64> = g.iter().map(|p| if p.is_zero() { 0 } else { poly::mask(p.lm(n)) }).collect();
        fs.iter().map(|t| Ok(export(&f, &ring, &poly::reduce(&f, &ring, import(&f, &ring, t)?, 0, &g, &masks, &active)))).collect()
    })
}

/// The division of `f` by `divisors`, which may include zeros, as Magma's
/// `NormalForm(f, S)` does it: the leading term of what is left is divided
/// by the first divisor whose leading monomial divides it, or else moves to
/// the remainder. Returns the remainder and the quotients.
pub fn divide(base: &Rc<Ctx>, n: usize, order: &Order, f: &Terms, divisors: &[Terms]) -> Result<(Terms, Vec<Terms>), Error> {
    let ring = Ring { n, order: order.clone() };
    with_field!(base, fld => {
        let (r, q) = poly::divide(&fld, &ring, import(&fld, &ring, f)?, &imports(&fld, &ring, divisors)?);
        Ok((export(&fld, &ring, &r), q.iter().map(|p| export(&fld, &ring, p)).collect()))
    })
}

/// The interreduction of `polys` as Magma's `Reduce` computes it: monic,
/// without zeros and sorted by decreasing leading monomial.
pub fn interreduce(base: &Rc<Ctx>, n: usize, order: &Order, polys: &[Terms]) -> Result<Vec<Terms>, Error> {
    let ring = Ring { n, order: order.clone() };
    with_field!(base, f => Ok(basis::interreduce(&f, &ring, imports(&f, &ring, polys)?).iter().map(|p| export(&f, &ring, p)).collect()))
}

/// The reduction of a Gröbner basis that need be neither minimal nor
/// reduced, as Magma's `ReduceGroebnerBasis` computes it.
pub fn reduce_basis(base: &Rc<Ctx>, n: usize, order: &Order, polys: &[Terms]) -> Result<Vec<Terms>, Error> {
    let ring = Ring { n, order: order.clone() };
    with_field!(base, f => Ok(basis::reduce_basis(&f, &ring, imports(&f, &ring, polys)?).iter().map(|p| export(&f, &ring, p)).collect()))
}

/// Whether `polys` is a Gröbner basis (not necessarily minimal or reduced)
/// of the ideal it generates.
pub fn is_groebner(base: &Rc<Ctx>, n: usize, order: &Order, polys: &[Terms]) -> Result<bool, Error> {
    let ring = Ring { n, order: order.clone() };
    with_field!(base, f => Ok(basis::is_groebner(&f, &ring, imports(&f, &ring, polys)?)))
}

/// The reduced Gröbner basis in the order `to` of the ideal of which `gb`
/// is the reduced Gröbner basis in the order `from`: for a zero-dimensional
/// ideal by a change of order, and otherwise computed again from `gb`.
pub fn change_order(base: &Rc<Ctx>, n: usize, from: &Order, gb: &[Terms], to: &Order) -> Result<Vec<Terms>, Error> {
    change_order_with(base, n, from, gb, to, Strategy::default())
}

/// As `change_order`, computed as `strategy` says.
pub fn change_order_with(base: &Rc<Ctx>, n: usize, from: &Order, gb: &[Terms], to: &Order, strategy: Strategy) -> Result<Vec<Terms>, Error> {
    let (ring, ring2) = (Ring { n, order: from.clone() }, Ring { n, order: to.clone() });
    let h = match field::coefficients(base).ok_or(Error::Unsupported)? {
        _ if modular(base, strategy) => modular::change_order(base, &ring, gb, &ring2)?,
        Coefficients::Zp(f) if f.modulus() < 1 << 31 => fglm::fglm(&f, &ring, &imports(&f, &ring, gb)?, &ring2).map(|h| exports(&f, &ring2, &h)),
        Coefficients::Zp(f) => fglm::fglm_field(&f, &ring, &imports(&f, &ring, gb)?, &ring2).map(|h| exports(&f, &ring2, &h)),
        Coefficients::Gr(f) => fglm::fglm_field(&f, &ring, &imports(&f, &ring, gb)?, &ring2).map(|h| exports(&f, &ring2, &h)),
    };
    match h {
        Some(h) => Ok(h),
        None => basis_of(base, &ring2, gb, None),
    }
}

/// Whether the order compares the degrees first, which suits the pairs of
/// F4 and Buchberger's algorithm taken by degree.
fn graded(order: &Order) -> bool {
    matches!(order, Order::GRevLex | Order::GLex | Order::GRevLexW(_))
}

/// A basis by F4 for the primes below 2^31, where it runs in word
/// arithmetic, and by Buchberger's algorithm for the other fields. As Magma
/// does, the basis in the other orders is computed in grevlex and changed to
/// the order, when the ideal is zero-dimensional. Over the rationals this
/// is the proven way.
fn basis_of(base: &Rc<Ctx>, ring: &Ring, gens: &[Terms], limit: Option<(&[u64], i128)>) -> Result<Vec<Terms>, Error> {
    match field::coefficients(base).ok_or(Error::Unsupported)? {
        Coefficients::Zp(f) if f.modulus() < 1 << 31 => Ok(exports(&f, ring, &words_basis(&f, ring, imports(&f, ring, gens)?, limit))),
        Coefficients::Zp(f) => changed_basis(&f, ring, gens, limit),
        Coefficients::Gr(f) => changed_basis(&f, ring, gens, limit),
    }
}

/// The basis over GF(p), p < 2^31, where F4 runs in words, of the ideal
/// generated by `polys`.
fn words_basis(f: &field::Zp, ring: &Ring, polys: Vec<Poly<u64>>, limit: Option<(&[u64], i128)>) -> Vec<Poly<u64>> {
    // F4 takes the pairs by degree, which suits graded orders and truncated
    // bases; in the other orders the degrees of the pairs can run far beyond
    // those of the basis.
    if limit.is_some() || graded(&ring.order) {
        // Pairs are taken by weighted degree for a grevlexw order.
        let weights = match (limit, &ring.order) {
            (Some((w, _)), _) => w.to_vec(),
            (None, Order::GRevLexW(w)) => w.clone(),
            _ => vec![1; ring.n],
        };
        return f4::groebner(f, ring, polys, &weights, limit.map(|(_, d)| d));
    }
    let grevlex = Ring { n: ring.n, order: Order::GRevLex };
    let g = f4::groebner(f, &grevlex, polys.iter().map(|p| reordered(f, p, &grevlex)).collect(), &vec![1; ring.n], None);
    fglm::fglm(f, &grevlex, &g, ring).unwrap_or_else(|| buchberger::groebner(f, ring, polys, None))
}

/// The polynomial `p` with its terms in the order of `ring`.
fn reordered<F: Field>(field: &F, p: &Poly<F::E>, ring: &Ring) -> Poly<F::E> {
    Poly::from_terms(field, ring, (0..p.len()).map(|i| (p.c[i].clone(), p.exp(i, ring.n).to_vec())).collect())
}

/// A basis by Buchberger's algorithm, in an order that is not graded by way
/// of grevlex for a zero-dimensional ideal.
fn changed_basis<F: Field>(field: &F, ring: &Ring, gens: &[Terms], limit: Option<(&[u64], i128)>) -> Result<Vec<Terms>, Error> {
    if limit.is_none() && !graded(&ring.order) {
        let grevlex = Ring { n: ring.n, order: Order::GRevLex };
        let g = buchberger::groebner(field, &grevlex, imports(field, &grevlex, gens)?, None);
        if let Some(h) = fglm::fglm_field(field, &grevlex, &g, ring) {
            return Ok(exports(field, ring, &h));
        }
    }
    groebner_in(field, ring, gens, limit)
}

fn exports<F: Field>(field: &F, ring: &Ring, polys: &[Poly<F::E>]) -> Vec<Terms> {
    polys.iter().map(|p| export(field, ring, p)).collect()
}

fn groebner_in<F: Field>(field: &F, ring: &Ring, gens: &[Terms], limit: Option<(&[u64], i128)>) -> Result<Vec<Terms>, Error> {
    let gens = imports(field, ring, gens)?;
    Ok(buchberger::groebner(field, ring, gens, limit).iter().map(|p| export(field, ring, p)).collect())
}

fn import<F: Field>(field: &F, ring: &Ring, t: &Terms) -> Result<Poly<F::E>, Error> {
    let exps = |e: &[u64]| e.iter().map(|&x| u32::try_from(x).map_err(|_| Error::ExponentTooLarge)).collect::<Result<Vec<u32>, Error>>();
    let terms = t.iter().map(|(c, e)| Ok((field.from_elem(c), exps(e)?))).collect::<Result<Vec<_>, Error>>()?;
    Ok(Poly::from_terms(field, ring, terms))
}

fn imports<F: Field>(field: &F, ring: &Ring, ts: &[Terms]) -> Result<Vec<Poly<F::E>>, Error> {
    ts.iter().map(|t| import(field, ring, t)).collect()
}

fn export<F: Field>(field: &F, ring: &Ring, p: &Poly<F::E>) -> Terms {
    (0..p.len()).map(|i| (field.to_elem(&p.c[i]), p.exp(i, ring.n).iter().map(|&x| x as u64).collect())).collect()
}

