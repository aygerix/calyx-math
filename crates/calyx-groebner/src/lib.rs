    /// The cyclic-n system.
    pub fn cyclic(ctx: &Rc<Ctx>, n: usize) -> Vec<Terms> {
        let one = || Elem::one(ctx).unwrap();
        let mut sys: Vec<Terms> = (1..n)
            .map(|k| {
                (0..n)
                    .map(|i| {
                        let mut e = vec![0u64; n];
                        (0..k).for_each(|j| e[(i + j) % n] += 1);
                        (one(), e)
                    })
                    .collect()
            })
            .collect();
        sys.push(vec![(one(), vec![1; n]), (Elem::from_i64(ctx, -1).unwrap(), vec![0; n])]);
        sys
    }

    /// The katsura-n system, in n + 1 variables.
    pub fn katsura(ctx: &Rc<Ctx>, n: usize) -> Vec<Terms> {
        let c = |k: i64| Elem::from_i64(ctx, k).unwrap();
        let var = |i: usize| (0..=n).map(|j| (i == j) as u64).collect::<Vec<u64>>();
        let mut sys: Vec<Terms> = (0..n)
            .map(|m| {
                let mut t = Terms::new();
                for l in -(n as i64)..=n as i64 {
                    let (a, b) = (l.unsigned_abs() as usize, (m as i64 - l).unsigned_abs() as usize);
                    if a <= n && b <= n {
                        t.push((c(1), var(a).iter().zip(var(b)).map(|(x, y)| x + y).collect()));
                    }
                }
                t.push((c(-1), var(m)));
                t
            })
            .collect();
        let mut lin: Terms = (1..=n).map(|l| (c(2), var(l))).collect();
        lin.push((c(1), var(0)));
        lin.push((c(-1), vec![0; n + 1]));
        sys.push(lin);
        sys
    }

