    #[test]
    fn modular_bases_over_the_rationals() {
        // The modular method gives the bases computed over the rationals, in
        // graded orders and others, for ideals of dimension zero or more.
        let q = Ctx::rationals();
        let orders = [Order::Lex, Order::GLex, Order::GRevLex, Order::ElimK(1), Order::Univ(1), Order::GRevLexW(vec![1, 2, 3])];
        let rational = Strategy { rational: true };
        let mut s = 0x9e3779b97f4a7c15;
        for round in 0..12 {
            let mut gens = random_system(&q, &mut s, 3, 2 + round % 2, 3, 2);
            for (i, g) in gens.iter_mut().enumerate() {
                let d = Elem::from_i64(&q, 3 * (i + round) as i64 + 2).unwrap();
                g.iter_mut().for_each(|(c, _)| *c = c.div(&d).unwrap());
            }
            for o in &orders {
                let m = groebner(&q, 3, o, &gens).unwrap();
                assert_eq!(shows("xyz", &m), shows("xyz", &groebner_with(&q, 3, o, &gens, rational).unwrap()), "{o:?}");
            }
        }
        // Primes dividing a leading coefficient or a denominator are passed
        // over, and so is the first prime here, whose basis has other leading
        // monomials than the others.
        for gens in [["2147483647*x - 1", "y^2 - 1/2147483629"], ["x*y - 2147483647", "x^2 - 1"]] {
            let gens: Vec<Terms> = gens.iter().map(|g| parse(&q, "xy", g)).collect();
            for o in [Order::Lex, Order::GRevLex] {
                assert_eq!(shows("xy", &groebner(&q, 2, &o, &gens).unwrap()), shows("xy", &groebner_with(&q, 2, &o, &gens, rational).unwrap()));
            }
        }
        let gens = [parse(&q, "xy", "x*y - 2147483647"), parse(&q, "xy", "x^2 - 1")];
        assert_eq!(shows("xy", &groebner(&q, 2, &Order::Lex, &gens).unwrap()), ["x - 1/2147483647*y", "y^2 - 4611686014132420609"]);
        // Katsura-5 in lex, whose coefficients take a few hundred primes.
        let k = katsura(&q, 5);
        let g = groebner(&q, 6, &Order::Lex, &k).unwrap();
        assert_eq!(shows("abcdef", &g), shows("abcdef", &groebner_with(&q, 6, &Order::Lex, &k, rational).unwrap()));
    }

    #[test]
    fn truncated_bases() {
        // The handbook's example of degree-d bases, as Magma 2.22 computes
        // it in the graded ring and then in the ungraded one.
        let q = Ctx::rationals();
        let l = ["a*b - c^2*d^3", "b*c*d + c^3", "c^2*d - d^5", "a*d - b*c"];
        let gens: Vec<Terms> = l.iter().map(|s| parse(&q, "abcd", s)).collect();
        let t = |order: &Order, weights: &[u64], d: i128| shows("abcd", &truncated_groebner(&q, 4, order, &gens, weights, d).unwrap());
        let (w, graded) = (Order::GRevLexW(vec![4, 3, 2, 1]), [4, 3, 2, 1]);
        assert_eq!((1..=10).map(|d| t(&w, &graded, d).len()).collect::<Vec<_>>(), [4, 4, 4, 4, 4, 4, 5, 6, 9, 9]);
        assert_eq!(t(&w, &graded, 5), ["a*b - d^7", "c^3 + a*d^2", "b*c - a*d", "c^2*d - d^5"]);
        assert_eq!(t(&w, &graded, 8), ["a*c*d^2 - b*d^5", "a*b - d^7", "a*d^3 + c*d^5", "c^3 + a*d^2", "b*c - a*d", "c^2*d - d^5"]);
        assert_eq!(t(&w, &graded, 11), shows("abcd", &groebner(&q, 4, &w, &gens).unwrap()));
        let g = Order::GRevLex;
        assert_eq!((1..=10).map(|d| t(&g, &[1; 4], d).len()).collect::<Vec<_>>(), [4, 4, 4, 5, 6, 12, 11, 11, 11, 11]);
        let d6 = [
            "a*c*d^4 - a*b^2",
            "a^2*b^3 + a^4*d",
            "a^2*b^2*d - a^3*b",
            "a^3*d^2 + a^2*b^2",
            "a^2*d^3 + a^2*b",
            "c^2*d^3 - a*b",
            "d^5 - c^2*d",
            "a^2*c*d + a^2*b",
            "a*c^2*d + a^2*d",
            "a*b*d^2 - a^2*d",
            "c^3 + a*d^2",
            "b*c - a*d",
        ];
        assert_eq!(t(&g, &[1; 4], 6), d6);
        // A pair counts by the degree of its lcm, even where its sugar is
        // larger, and what it adds is kept whatever its degree.
        let p = gf(7);
        let gens: Vec<Terms> = ["x*y - y^4", "x^2 - y"].iter().map(|s| parse(&p, "xy", s)).collect();
        let t = |d: i128| shows("xy", &truncated_groebner(&p, 2, &Order::Lex, &gens, &[1, 1], d).unwrap());
        assert_eq!(t(2), ["x^2 + 6*y", "x*y + 6*y^4"]);
        assert_eq!(t(3), ["x^2 + 6*y", "x*y + 6*y^4", "y^7 + 6*y^2"]);
        assert_eq!(t(-1), ["x^2 + 6*y", "x*y + 6*y^4"]);
    }

    /// `NormalForm(f, S)` with its coordinates, over the field `ctx` in lex.
    fn division(ctx: &Rc<Ctx>, vars: &str, f: &str, s: &[&str]) -> (String, Vec<String>) {
        let s: Vec<Terms> = s.iter().map(|g| parse(ctx, vars, g)).collect();
        let (r, q) = divide(ctx, vars.len(), &Order::Lex, &parse(ctx, vars, f), &s).unwrap();
        (show(vars, &r), shows(vars, &q))
    }

    #[test]
    fn division_as_in_magma() {
        let q = Ctx::rationals();
        assert_eq!(division(&q, "xyz", "x^3*y", &["y^2 - x", "x*y - 1"]), ("y^7".into(), vec!["-x^2*y - x*y^3 - y^5".into(), "0".into()]));
        let (r, c) = division(&q, "xyz", "2*x^3*y + 3*y^3", &["3*x*y - 1", "2*y^2 - x"]);
        assert_eq!((r.as_str(), c), ("3*y^3 + 4/9*y", vec!["2/3*x^2 + 4/9*y".to_string(), "-2/3*x".to_string()]));
        let (r, c) = division(&q, "xyz", "x^2 + y", &["x - 1", "0", "x"]);
        assert_eq!((r.as_str(), c), ("y + 1", vec!["x + 1".to_string(), "0".to_string(), "0".to_string()]));
        let (r, c) = division(&q, "xyz", "x*y*z - 1", &["x*y - z", "0", "x*z - y"]);
        assert_eq!((r.as_str(), c), ("z^2 - 1", vec!["z".to_string(), "0".to_string(), "0".to_string()]));
        let (r, c) = division(&gf(7), "st", "s^3 + t", &["2*s - t", "t^2 - 1"]);
        assert_eq!((r.as_str(), c), ("2*t", vec!["4*s^2 + 2*s*t + t^2".to_string(), "t".to_string()]));
        // The divisors are tried in the order given.
        let nf = |s: &[&str]| {
            let s: Vec<Terms> = s.iter().map(|g| parse(&q, "xy", g)).collect();
            let fs: Vec<Terms> = ["x^2", "x*y + y^3"].iter().map(|f| parse(&q, "xy", f)).collect();
            shows("xy", &normal_forms(&q, 2, &Order::Lex, &fs, &s).unwrap())
        };
        assert_eq!(nf(&["x*y - 1", "y^2 - x"]), ["y", "y^3 + 1"]);
        assert_eq!(nf(&["y^2 - x", "x*y - 1"]), ["y^4", "2*y^3"]);
        assert_eq!(nf(&[]), ["x^2", "x*y + y^3"]);
    }

