    fn random_system(ctx: &Rc<Ctx>, s: &mut u64, n: usize, count: usize, terms: usize, deg: u64) -> Vec<Terms> {
        let mut next = || {
            *s ^= *s << 13;
            *s ^= *s >> 7;
            *s ^= *s << 17;
            *s
        };
        (0..count)
            .map(|_| {
                (0..terms)
                    .map(|_| {
                        let mut e = vec![0u64; n];
                        (0..next() % (deg + 1)).for_each(|_| e[(next() % n as u64) as usize] += 1);
                        (Elem::from_i64(ctx, (next() % 201) as i64 - 100).unwrap(), e)
                    })
                    .collect()
            })
            .collect()
    }

