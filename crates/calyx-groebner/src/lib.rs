    /// Check that `g` is the reduced Gröbner basis in `order` of the ideal
    /// generated by `gens`, sorted as Magma sorts it.
    fn check_reduced<F: Field>(field: &F, ring: &Ring, gens: &[Poly<F::E>], g: &[Poly<F::E>]) {
        let n = ring.n;
        let masks: Vec<u64> = g.iter().map(|p| poly::mask(p.lm(n))).collect();
        let all: Vec<usize> = (0..g.len()).collect();
        let nf = |f: &Poly<F::E>| poly::reduce(field, ring, f.clone(), 0, g, &masks, &all);
        for w in g.windows(2) {
            assert_eq!(ring.cmp(w[0].lm(n), w[1].lm(n)), std::cmp::Ordering::Greater);
        }
        for (k, p) in g.iter().enumerate() {
            assert!(field.is_one(p.lc()));
            for i in 0..p.len() {
                assert!((0..p.len()).skip(1).all(|j| ring.cmp(p.exp(j - 1, n), p.exp(j, n)).is_gt()));
                assert!(g.iter().enumerate().all(|(j, q)| j == k || !poly::divides(q.lm(n), p.exp(i, n))), "not reduced");
            }
            for q in &g[k + 1..] {
                let l = poly::lcm(p.lm(n), q.lm(n));
                let s = poly::sub_mul(field, ring, &p.shift(&poly::quotient(&l, p.lm(n)), n), 1, &field.one(), &poly::quotient(&l, q.lm(n)), q, 1);
                assert!(nf(&s).is_zero(), "an S-polynomial does not reduce to zero");
            }
        }
        assert!(gens.iter().all(|f| nf(f).is_zero()), "a generator is not in the ideal of the basis");
    }

    /// The Gröbner basis of `gens` in `order`, checked as above and against
    /// the one in `other`: each reduces the other to zero.
    fn checked<F: Field>(field: &F, n: usize, order: &Order, other: &Order, gens: &[Terms]) -> Vec<Poly<F::E>> {
        let (ring, ring2) = (Ring { n, order: order.clone() }, Ring { n, order: other.clone() });
        let polys = |r: &Ring| gens.iter().map(|t| import(field, r, t).unwrap()).collect::<Vec<_>>();
        let (g, g2) = (buchberger::groebner(field, &ring, polys(&ring), None), buchberger::groebner(field, &ring2, polys(&ring2), None));
        check_reduced(field, &ring, &polys(&ring), &g);
        check_reduced(field, &ring2, &polys(&ring2), &g2);
        let back = |p: &Poly<F::E>, r: &Ring| import(field, r, &export(field, &ring2, p)).unwrap();
        check_reduced(field, &ring, &g2.iter().map(|p| back(p, &ring)).collect::<Vec<_>>(), &g);
        g
    }

