    /// A polynomial in the variables `vars` written as Magma prints it, such
    /// as `x^2*y - 3/2*z + 1`.
    pub fn parse(ctx: &Rc<Ctx>, vars: &str, s: &str) -> Terms {
        let names: Vec<char> = vars.chars().collect();
        let s: String = s.chars().filter(|c| !c.is_whitespace()).collect();
        let s = if s.starts_with('-') { s } else { format!("+{s}") };
        let mut terms = Terms::new();
        let mut rest = s.as_str();
        while !rest.is_empty() {
            let neg = rest.starts_with('-');
            rest = &rest[1..];
            let end = rest.find(['+', '-']).unwrap_or(rest.len());
            let (term, tail) = rest.split_at(end);
            rest = tail;
            let mut coeff = Rational::one();
            let mut e = vec![0u64; names.len()];
            for factor in term.split('*') {
                if factor.starts_with(|c: char| c.is_ascii_digit()) {
                    coeff = Rational::parse(factor).unwrap();
                } else {
                    let (v, k) = factor.split_once('^').unwrap_or((factor, "1"));
                    let i = names.iter().position(|&c| v.starts_with(c)).unwrap();
                    e[i] += k.parse::<u64>().unwrap();
                }
            }
            if neg {
                coeff = -&coeff;
            }
            let c = match ctx.kind() {
                CtxKind::Rationals => Elem::from_rational(ctx, &coeff).unwrap(),
                _ => Elem::from_integer(ctx, &coeff.numerator()).unwrap().div(&Elem::from_integer(ctx, &coeff.denominator()).unwrap()).unwrap(),
            };
            terms.push((c, e));
        }
        terms
    }

    /// Print a polynomial as Magma does, its terms in the order given.
    pub fn show(vars: &str, t: &Terms) -> String {
        let names: Vec<char> = vars.chars().collect();
        let mut out = String::new();
        for (c, e) in t {
            let q = match c.ctx().kind() {
                CtxKind::Rationals => c.to_rational().unwrap(),
                _ => Rational::from_integer(&c.to_integer().unwrap_or_else(|_| Integer::from_u64(c.to_word().unwrap()))),
            };
            let power = |k: u64, v: char| if k == 1 { v.to_string() } else { format!("{v}^{k}") };
            let mono: Vec<String> = e.iter().zip(&names).filter(|(k, _)| **k > 0).map(|(k, v)| power(*k, *v)).collect();
            let (neg, a) = (q.sign() < 0, q.abs());
            if out.is_empty() {
                out.push_str(if neg { "-" } else { "" });
            } else {
                out.push_str(if neg { " - " } else { " + " });
            }
            match (a.is_one(), mono.is_empty()) {
                (true, false) => out.push_str(&mono.join("*")),
                (_, true) => out.push_str(&a.to_string()),
                _ => out.push_str(&format!("{a}*{}", mono.join("*"))),
            }
        }
        if out.is_empty() { "0".into() } else { out }
    }

    pub fn gb(ctx: &Rc<Ctx>, vars: &str, order: &Order, gens: &[&str]) -> Vec<String> {
        let gens: Vec<Terms> = gens.iter().map(|s| parse(ctx, vars, s)).collect();
        groebner(ctx, vars.len(), order, &gens).unwrap().iter().map(|t| show(vars, t)).collect()
    }

