        let l = ["a*b - c^2*d^3", "b*c*d + c^3", "c^2*d - d^5", "a*d - b*c"];
        let gens: Vec<Terms> = l.iter().map(|s| parse(&q, "abcd", s)).collect();
        let t = |order: &Order, weights: &[u64], d: i128| shows("abcd", &truncated_groebner(&q, 4, order, &gens, weights, d).unwrap());
        let (w, graded) = (Order::GRevLexW(vec![4, 3, 2, 1]), [4, 3, 2, 1]);
        assert_eq!((1..=10).map(|d| t(&w, &graded, d).len()).collect::<Vec<_>>(), [4, 4, 4, 4, 4, 4, 5, 6, 9, 9]);
