// IsIdentical: small integers and rationals, and elements of residue rings,
// prime fields and fields with Zech logarithms, are identical when equal;
// other objects only to themselves and their copies (#49).
Z := Integers();
IsIdentical(Z, Integers());
I := ideal<Z | 12>;
IsIdentical(I, ideal<Z | 12>);
IsIdentical(1, 1);
IsIdentical(2^100, 2^100);
IsIdentical([1], [1]);
x := [1]; y := x; IsIdentical(x, y);
IsIdentical(GF(5), GF(5));
IsIdentical(GF(5, 2), GF(25));
IsIdentical(PolynomialRing(Z), PolynomialRing(Z));
IsIdentical(PolynomialRing(Z : Global := false), PolynomialRing(Z : Global := false));
IsIdentical(1, 1/1);
IsIdentical("a", "a");
IsIdentical(1, "a");
IsIdentical(Rationals(), RationalField());
IsIdentical(<1>, <1>);
IsIdentical({1}, {1});
IsIdentical(true, true);
P<t> := PolynomialRing(Z); IsIdentical(t, P.1); IsIdentical(t^2, t^2);
IsIdentical(Integers(6), Integers(6));
IsIdentical(GF(5)!1, GF(5)!1);
F<w> := GF(2^10); IsIdentical(w, w^1); IsIdentical(w^3, w^3);
IsIdentical(1/2, 1/2); x := 1/2; y := x; IsIdentical(x, y);
s := "abc"; t := s; IsIdentical(s, t);
IsIdentical(2^100 div 2^99, 2);
IsIdentical(Integers(), Rationals());
IsIdentical(Integers(), 1);
[IsIdentical(2^k, 2^k) : k in [29, 30, 31, 32, 61, 62, 63, 64]];
[IsIdentical(-2^k, -2^k) : k in [29, 30, 31, 32, 62, 63, 64]];
[IsIdentical(1/2^k, 1/2^k) : k in [10, 29, 30, 31, 61, 62, 63, 70]];
IsIdentical(3/7, 3/7);
IsIdentical(GF(10007)!5, GF(10007)!5);
IsIdentical(GF(2^31-1)!5, GF(2^31-1)!5);
IsIdentical(GF(NextPrime(2^62))!5, GF(NextPrime(2^62))!5);
F<w> := GF(3^20); IsIdentical(w^3, w^3);
IsIdentical(Integers(10)!3, Integers(10)!3);
[IsIdentical(1/2^k, 1/2^k) : k in [11..29]];
[IsIdentical(2^k/3, 2^k/3) : k in [11..29]];
[IsIdentical(-1/2^k, -1/2^k) : k in [11..16]];
IsIdentical(Integers(10^30)!3, Integers(10^30)!3);
IsIdentical(GF(NextPrime(10^30))!3, GF(NextPrime(10^30))!3);
F<w> := GF(7^8); IsIdentical(w^3, w^3);
F<w> := GF(2^20); IsIdentical(w^3, w^3);
IsIdentical(RngIntElt, RngIntElt);
IsIdentical(Infinity(), Infinity());
