/// A lexical token.
#[derive(Clone, Debug, PartialEq)]
pub enum Tok {
    /// An identifier, including quoted names such as `'+'`.
    Ident(String),
    /// A decimal integer literal (digits only).
    Int(String),
    /// A real literal, as written.
    Real(String),
    /// A string literal with escapes resolved.
    Str(String),
    Kw(Kw),
    /// `name o:=` mutation assignment, e.g. `+:=` or `join:=`.
    OpAssign(String),
    /// `$1`, `$2`, ...
    Dollar(u32),
    /// `$$`
    DollarDollar,
    Underscore,

    LParen,
    RParen,
    LBrack,
    RBrack,
    LBrace,
    RBrace,
    /// `{@`
    LBraceAt,
    /// `@}`
    AtRBrace,
    /// `{*`
    LBraceStar,
    /// `*}`
    StarRBrace,
    /// `{!`
    LBraceBang,
    /// `!}`
    BangRBrace,
    /// `[*`
    LBrackStar,
    /// `*]`
    StarRBrack,
    /// `[!`
    LBrackBang,
    /// `!]`
    BangRBrack,
    Lt,
    Gt,
    Comma,
    Semi,
    Colon,
    Dot,
    DotDot,
    Ellipsis,
    Assign,
    Plus,
    Minus,
    Star,
    Slash,
    Caret,
    CaretCaret,
    Hash,
    Tilde,
    Bang,
    BangBang,
    At,
    AtAt,
    Backquote,
    DoubleBackquote,
    Arrow,
    MapsTo,
    Pipe,
    Amp,
    Equals,
    Question,
    /// A malformed token; the message explains why.
    Error(String),
    /// Input ended inside a string or comment.
    Unterminated(String),
    Eof,
}

impl Tok {
    pub fn describe(&self) -> String {
        match self {
            Tok::Ident(s) => format!("identifier '{s}'"),
            Tok::Int(s) | Tok::Real(s) => format!("'{s}'"),
            Tok::Str(_) => "string".to_string(),
            Tok::Kw(k) => format!("'{}'", kw_text(*k)),
            Tok::OpAssign(o) => format!("'{o}:='"),
            Tok::Dollar(n) => format!("'${n}'"),
            Tok::Eof => "end of input".to_string(),
            Tok::Error(m) | Tok::Unterminated(m) => m.clone(),
            t => format!("'{}'", punct_text(t)),
        }
    }
}

