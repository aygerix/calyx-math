fn punct_text(t: &Tok) -> &'static str {
    match t {
        Tok::DollarDollar => "$$",
        Tok::Underscore => "_",
        Tok::LParen => "(",
        Tok::RParen => ")",
        Tok::LBrack => "[",
        Tok::RBrack => "]",
        Tok::LBrace => "{",
        Tok::RBrace => "}",
        Tok::LBraceAt => "{@",
        Tok::AtRBrace => "@}",
        Tok::LBraceStar => "{*",
        Tok::StarRBrace => "*}",
        Tok::LBraceBang => "{!",
        Tok::BangRBrace => "!}",
        Tok::LBrackStar => "[*",
        Tok::StarRBrack => "*]",
        Tok::LBrackBang => "[!",
        Tok::BangRBrack => "!]",
        Tok::Lt => "<",
        Tok::Gt => ">",
        Tok::Comma => ",",
        Tok::Semi => ";",
        Tok::Colon => ":",
        Tok::Dot => ".",
        Tok::DotDot => "..",
        Tok::Ellipsis => "...",
        Tok::Assign => ":=",
        Tok::Plus => "+",
        Tok::Minus => "-",
        Tok::Star => "*",
        Tok::Slash => "/",
        Tok::Caret => "^",
        Tok::CaretCaret => "^^",
        Tok::Hash => "#",
        Tok::Tilde => "~",
        Tok::Bang => "!",
        Tok::BangBang => "!!",
        Tok::At => "@",
        Tok::AtAt => "@@",
        Tok::Backquote => "`",
        Tok::DoubleBackquote => "``",
        Tok::Arrow => "->",
        Tok::MapsTo => ":->",
        Tok::Pipe => "|",
        Tok::Amp => "&",
        Tok::Equals => "=",
        Tok::Question => "?",
        _ => "?",
    }
}

